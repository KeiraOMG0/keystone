"""
Dashboard "Roles" page (/dashboard/roles): create, edit, reorder, duplicate
and delete Discord roles, view and change role members.

GET    /api/roles                                  overview (roles, bot hierarchy info, permission catalogue)
POST   /api/roles                                  create
PATCH  /api/roles/{role_id}                        edit (Discord fields and/or internal bot permissions)
POST   /api/roles/{role_id}/move                   reorder {position}
POST   /api/roles/{role_id}/duplicate              copy {name?}
DELETE /api/roles/{role_id}                        delete {confirm_name}
GET    /api/roles/{role_id}/members?offset&limit&q members with the role
POST   /api/roles/{role_id}/members/{user_id}      give the role to a member
DELETE /api/roles/{role_id}/members/{user_id}      take the role away
GET    /api/roles/member-search?q=                 user picker for the above

Gating: require_staff on every route, NOT a grantable permission, for the same
reason as the Permissions page: this page can create roles carrying Discord
permissions and internal bot grants, so gating it on a grant would let a role
escalate itself. The acting user (id + username, used for the audit row and the
Discord audit-log reason "Dashboard: <username>") always comes from the
session, never the request body. Every rule is enforced by the bot
(services/role_admin_service.py): the bot's hierarchy and held permissions,
managed roles, AND the acting user's own hierarchy (non-owners may only touch
roles below their top role, grant only permissions they hold, never
Administrator, and never give themselves a role). The overview passes the
session user so `manageable` reflects both.

Error mapping: internal 400/403/404/409/422 keep their {"error", "message"}
detail (generated by the bot, safe for staff); a 403 from Discord comes back as
409 {"error": "discord_forbidden"} so the frontend never confuses it with a
dashboard 403 ("forbidden" -> Forbidden403 page). Unreachable bot -> 502
{"error": "internal_api_unavailable"}.
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, Query, status
from pydantic import BaseModel, Field, field_validator

from server import config
from server.db.models import Session
from server.permissions.guards import require_staff
from server.services import internal_client
from server.services.internal_client import InternalAPIError

router = APIRouter(prefix="/api/roles", tags=["roles"])


def _snowflake(value: str) -> int:
    if not isinstance(value, str) or not value.isdigit() or not (15 <= len(value) <= 21):
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail={"error": "invalid_id", "message": "Not a Discord ID."})
    return int(value)


def _translate(exc: InternalAPIError) -> HTTPException:
    code = exc.status_code
    detail = exc.detail if isinstance(exc.detail, dict) else None
    if code in (400, 404, 409, 422):
        if detail is None:
            detail = {"error": "invalid_request" if code in (400, 422) else ("not_found" if code == 404 else "conflict")}
        return HTTPException(status_code=400 if code == 422 else code, detail=detail)
    if code == 403:
        # Discord / hierarchy refusal, never a dashboard authorization failure.
        if detail is None or detail.get("error") == "forbidden":
            detail = {"error": "discord_forbidden", "message": "Discord refused the change."}
        return HTTPException(status_code=status.HTTP_409_CONFLICT, detail=detail)
    if code == 502 and detail is not None:
        return HTTPException(status_code=status.HTTP_502_BAD_GATEWAY, detail=detail)
    return HTTPException(status_code=status.HTTP_502_BAD_GATEWAY, detail={"error": "internal_api_unavailable"})


def _actor(session: Session) -> dict:
    return {"actor_id": session.discord_user_id, "actor_name": (session.discord_username or "")[:100] or None}


_GUILD = lambda: config.DASHBOARD_GUILD_ID  # noqa: E731 - read at call time (tests patch config)


class CreateRoleBody(BaseModel):
    name: str = Field(min_length=1, max_length=100)
    color: str | None = Field(default=None, max_length=7)
    hoist: bool = False
    mentionable: bool = False
    permissions: list[str] = Field(default_factory=list, max_length=80)
    position: int | None = Field(default=None, ge=1, le=250)
    above_role_id: str | None = Field(default=None, pattern=r"^\d{15,21}$")
    unicode_emoji: str | None = Field(default=None, max_length=16)
    icon_base64: str | None = Field(default=None, max_length=400_000)
    internal_permissions: list[str] = Field(default_factory=list, max_length=32)
    confirm_administrator: bool = False


class UpdateRoleBody(BaseModel):
    name: str | None = Field(default=None, min_length=1, max_length=100)
    color: str | None = Field(default=None, max_length=7)
    hoist: bool | None = None
    mentionable: bool | None = None
    permissions: list[str] | None = Field(default=None, max_length=80)
    unicode_emoji: str | None = Field(default=None, max_length=16)
    icon_base64: str | None = Field(default=None, max_length=400_000)
    clear_icon: bool = False
    internal_permissions: list[str] | None = Field(default=None, max_length=32)
    confirm_administrator: bool = False


class MoveBody(BaseModel):
    position: int = Field(ge=1, le=250)


class DuplicateBody(BaseModel):
    name: str | None = Field(default=None, min_length=1, max_length=100)
    confirm_administrator: bool = False


class DeleteBody(BaseModel):
    confirm_name: str = Field(min_length=1, max_length=100)

    @field_validator("confirm_name")
    @classmethod
    def _strip(cls, v: str) -> str:
        return v.strip()


@router.get("")
async def overview(session: Session = Depends(require_staff)) -> dict:
    try:
        return await internal_client.get_role_admin_overview(_GUILD(), session.discord_user_id)
    except InternalAPIError as exc:
        raise _translate(exc)


@router.get("/member-search")
async def member_search(
    q: str = Query(..., min_length=2, max_length=100),
    session: Session = Depends(require_staff),
) -> dict:
    try:
        return await internal_client.search_members(_GUILD(), q, 10)
    except InternalAPIError as exc:
        raise _translate(exc)


@router.post("", status_code=status.HTTP_201_CREATED)
async def create_role(body: CreateRoleBody, session: Session = Depends(require_staff)) -> dict:
    try:
        payload = body.model_dump()
        payload["above_role_id"] = int(body.above_role_id) if body.above_role_id else None
        return await internal_client.create_role_admin(_GUILD(), {**payload, **_actor(session)})
    except InternalAPIError as exc:
        raise _translate(exc)


@router.patch("/{role_id}")
async def update_role(role_id: str, body: UpdateRoleBody, session: Session = Depends(require_staff)) -> dict:
    rid = _snowflake(role_id)
    try:
        return await internal_client.update_role_admin(_GUILD(), rid, {**body.model_dump(), **_actor(session)})
    except InternalAPIError as exc:
        raise _translate(exc)


